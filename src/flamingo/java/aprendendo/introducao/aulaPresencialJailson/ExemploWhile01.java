package flamingo.java.aprendendo.introducao.aulaPresencialJailson;

public class ExemploWhile01 {
	static void main(String[] args) {
		int contadora=0;
		//while -> enquanto
		//(contadora<10) -> teste de controle
		while (contadora<10){
			System.out.printf("Yuri apareceu %d\n",(contadora+1));
			contadora++;
		}
	}
}
